#!/usr/bin/env python3
"""Collect notices from the pinned macOS/Windows runtime dependencies."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "resources" / "licenses"
TARGETS = ("darwin/amd64", "darwin/arm64", "windows/amd64", "windows/arm64")
LEGAL = ("LICENSE*", "NOTICE*", "COPYING*", "COPYRIGHT*", "AUTHORS*", "OFL*", "PATENTS*", "THIRD_PARTY_NOTICES*")
EXTRA = {
    "github.com/MichaelKinsy/PiG": ("LICENSES/*", "third_party/*/LICENSE*", "third_party/*/NOTICE*"),
    "github.com/egoist/mygo": ("internal/shader/LICENSE", "plugins/*/LICENSE"),
    "github.com/oneo-me/onevra/source": ("icons/lucide/LICENSE", "components/LICENSE.mygo"),
}


def go(*args, env=None):
    return subprocess.check_output(["go", *args], cwd=ROOT, env=env, text=True).strip()


def generate():
    modules = {}
    for target in TARGETS:
        system, arch = target.split("/")
        env = os.environ | {"GOWORK": "off", "CGO_ENABLED": "0", "GOOS": system, "GOARCH": arch}
        lines = go("list", "-deps", "-f", '{{with .Module}}{{.Path}}{{"\\t"}}{{.Version}}{{"\\t"}}{{.Dir}}{{end}}', ".", env=env)
        for line in lines.splitlines():
            if not line:
                continue
            module, version, directory = line.split("\t")
            if version:
                modules[module] = (version, Path(directory))
    modules["Go standard library"] = (go("env", "GOVERSION"), Path(go("env", "GOROOT")))
    records = []
    text = ["Third-party notices for Wada\nGenerated by scripts/licenses.py; do not edit.\n"]
    for module, (version, directory) in sorted(modules.items()):
        patterns = (*LEGAL, *EXTRA.get(module, ()))
        if module == "Go standard library":
            patterns = ("LICENSE", "PATENTS")
        files = sorted({path for pattern in patterns for path in directory.glob(pattern) if path.is_file()})
        if not any(path.name.startswith(("LICENSE", "COPYING", "OFL")) for path in files):
            raise SystemExit(f"No license found for {module}@{version}; resolve before distribution")
        notices = []
        text.append(f"\n{'=' * 72}\n{module} {version}\n")
        for path in files:
            data = path.read_bytes()
            relative = path.relative_to(directory).as_posix()
            notices.append({"file": relative, "sha256": hashlib.sha256(data).hexdigest()})
            text.append(f"\n--- {relative} ---\n{data.decode('utf-8').rstrip()}\n")
        records.append({"module": module, "version": version, "notices": notices})
    inventory = {"targets": TARGETS, "modules": records}
    generated = {"DEPENDENCIES.txt": "".join(text), "inventory.json": json.dumps(inventory, indent=2) + "\n"}
    pig = modules["github.com/MichaelKinsy/PiG"][1]
    for name in ("LICENSE", "NOTICE", "THIRD_PARTY_NOTICES.md"):
        generated[f"pig/{name}"] = (pig / name).read_text()
    return generated


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated notices are stale")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        stale = [name for name, content in generated.items() if not (OUTPUT / name).is_file() or (OUTPUT / name).read_text() != content]
        if stale:
            raise SystemExit("Stale license inventory: " + ", ".join(stale) + "; run make licenses")
        print("License inventory matches pinned macOS/Windows dependencies.")
    else:
        OUTPUT.mkdir(parents=True, exist_ok=True)
        for name, content in generated.items():
            (OUTPUT / name).parent.mkdir(parents=True, exist_ok=True)
            (OUTPUT / name).write_text(content)
        print("Updated dependency notices and inventory.")


if __name__ == "__main__":
    main()
